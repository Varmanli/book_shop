export function getProvinceCities(province: string) {
  return IRAN_PROVINCES.find((item) => item.value === province)?.cities ?? [];
}

export function isValidProvince(province: string) {
  return IRAN_PROVINCES.some((item) => item.value === province);
}

export function isValidCity(province: string, city: string) {
  return getProvinceCities(province).includes(city);
}
